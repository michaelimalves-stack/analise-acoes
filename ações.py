import pandas as pd
import numpy as np
import yfinance as yf
import matplotlib.pyplot as plt

Carteira = ["PETR4.SA","VALE3.SA","ITUB4.SA"]
dados = yf.download(
    Carteira,
  period = "4y",
  auto_adjust=True
  )
print(dados.head())

#Retorno Acumulado
preco = dados ["Close"]
retorno_acumulado = (
    preco.iloc[-1]
    /preco.iloc[0]
    -1) * 100
print('Retorno acumulado dos ultimos 4 anos (%):')
print(retorno_acumulado.round(2))

# Duração do histórico em anos
anos = (preco.index[-1] - preco.index[0]).days / 365.25

# Retorno anualizado em porcentagem
retorno_anualizado = (
    (preco.iloc[-1] / preco.iloc[0]) ** (1 / anos) - 1
) * 100

print('Retorno anualizado (% ao ano):')
print(retorno_anualizado.round(2))

# Calcula os retornos diários
retorno_diario = preco.pct_change(fill_method=None).dropna()

# Calcula e anualiza a volatilidade
volatilidade_anual = retorno_diario.std() * np.sqrt(252) * 100

print('Volatilidade anualizada (%):')
print(volatilidade_anual.round(2))

# Maior preço atingido acumulado até cada data
Pico_acumulado = preco.cummax()

# Queda percentual em relação ao pico anterior (Drawdown)
drawdown = (preco / Pico_acumulado - 1) * 100

# Maior Queda (Drawdown Máximo) de cada Ação
Queda_maxima = drawdown.min()

print('Queda máxima (%):')
print(Queda_maxima.round(2))

# Calcula a correlação entre os retornos diários
correlacao = retorno_diario.corr()

print('Correlação entre as ações:')
print(correlacao.round(2))

resumo = pd.DataFrame({
    'Retorno acumulado (%)': retorno_acumulado,
    'Retorno anualizado (%)': retorno_anualizado,
    'Volatilidade anualizada (%)': volatilidade_anual,
    'Queda máxima (%)': Queda_maxima
})

print(resumo.round(2).to_string())

# Faz todas as ações começarem com R$ 1.000
evolucao = (preco / preco.iloc[0]) * 1000

# Cria o gráfico
evolucao.plot(figsize=(12, 6))

plt.title('Evolução de R$ 1.000 em cada ação')
plt.xlabel('Data')
plt.ylabel('Valor acumulado (R$)')
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

print('Maior retorno acumulado:', retorno_acumulado.idxmax())

print('Menor volatilidade:', volatilidade_anual.idxmin())

print('Queda máxima menos intensa:', Queda_maxima.idxmax())

print(resumo.round(2).to_string())

